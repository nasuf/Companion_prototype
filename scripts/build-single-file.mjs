import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const outDir = path.join(rootDir, "dist");
const outFile = path.join(outDir, "companion.html");
const assetCache = new Map();

const mimeByExt = {
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".webp": "image/webp",
  ".gif": "image/gif",
  ".avif": "image/avif"
};

function mimeFor(filePath) {
  return mimeByExt[path.extname(filePath).toLowerCase()] || "application/octet-stream";
}

async function assetToDataUrl(assetPath) {
  const normalized = assetPath.replace(/\\/g, "/");
  if (assetCache.has(normalized)) return assetCache.get(normalized);

  const absolute = path.resolve(rootDir, normalized);
  if (!absolute.startsWith(rootDir + path.sep)) {
    throw new Error(`Refusing to inline asset outside project: ${assetPath}`);
  }

  const bytes = await readFile(absolute);
  const dataUrl = `data:${mimeFor(absolute)};base64,${bytes.toString("base64")}`;
  assetCache.set(normalized, dataUrl);
  return dataUrl;
}

async function inlineAssetReferences(content) {
  const assetRefPattern = /assets\/[^\s"'`)<>]+/g;
  const refs = [...new Set(content.match(assetRefPattern) || [])];
  let output = content;

  for (const ref of refs) {
    const dataUrl = await assetToDataUrl(ref);
    output = output.split(ref).join(dataUrl);
  }

  return output;
}

function escapeInlineScript(js) {
  return js.replaceAll("</script", "<\\/script");
}

function escapeInlineStyle(css) {
  return css.replaceAll("</style", "<\\/style");
}

async function inlineStyles(html) {
  const linkPattern = /<link\b(?=[^>]*\brel=["']stylesheet["'])(?=[^>]*\bhref=["']([^"']+)["'])[^>]*>/gi;
  let output = html;
  const matches = [...html.matchAll(linkPattern)];

  for (const match of matches) {
    const href = match[1];
    const cssPath = path.resolve(rootDir, href);
    let css = await readFile(cssPath, "utf8");
    css = await inlineAssetReferences(css);
    const inlineTag = `<style data-inline-from="${href}">\n${escapeInlineStyle(css)}\n</style>`;
    output = output.replace(match[0], inlineTag);
  }

  return output;
}

async function inlineScripts(html) {
  const scriptPattern = /<script\b(?=[^>]*\bsrc=["']([^"']+)["'])\s*[^>]*><\/script>/gi;
  let output = html;
  const matches = [...html.matchAll(scriptPattern)];

  for (const match of matches) {
    const src = match[1];
    const jsPath = path.resolve(rootDir, src);
    let js = await readFile(jsPath, "utf8");
    js = await inlineAssetReferences(js);
    const inlineTag = `<script data-inline-from="${src}">\n${escapeInlineScript(js)}\n</script>`;
    output = output.replace(match[0], inlineTag);
  }

  return output;
}

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}

async function build() {
  const indexPath = path.join(rootDir, "index.html");
  let html = await readFile(indexPath, "utf8");

  html = await inlineStyles(html);
  html = await inlineScripts(html);
  html = await inlineAssetReferences(html);

  const banner = [
    "<!--",
    "  Generated by scripts/build-single-file.mjs.",
    "  This file is self-contained: CSS, JavaScript, and local assets are inlined.",
    "-->"
  ].join("\n");

  html = html.replace("<!doctype html>", `<!doctype html>\n${banner}`);

  await mkdir(outDir, { recursive: true });
  await writeFile(outFile, html, "utf8");

  const byteLength = Buffer.byteLength(html);
  console.log(`Built ${path.relative(rootDir, outFile)} (${formatBytes(byteLength)})`);
  console.log(`Inlined ${assetCache.size} asset(s).`);
}

build().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
